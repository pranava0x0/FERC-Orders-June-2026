// Generate sources/filings/order-anchors.json: the citable directives of the seven June 18, 2026
// orders (E-7 to E-12 and E-2), one stable id per directive, from data.js. Per-document readings
// cite these ids to state their connection to the show cause orders.
//   node tools/build-order-anchors.mjs [--check]
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { loadData } from "./build-seo.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "sources", "filings", "order-anchors.json");
const slugify = (s) => s.normalize("NFKD").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const REFORMS = new Set(["study", "cost", "colo", "flex", "proximate", "registry", "adequacy", "procedure"]);
// Ids cut at a word boundary so they stay readable in JSON that cites them.
const idOf = (t) => { const s = slugify(t); if (s.length <= 36) return s; const cut = s.slice(0, 37); return cut.slice(0, cut.lastIndexOf("-")); };

// Two directives every §206 order shares, found on the page rather than typed: the 60-day choice
// (show cause or propose changes) and the 30-day informational report on resource adequacy.
const COMMON = [
  { key: "show-cause", label: "Show cause or propose tariff changes in 60 days", reform: "procedure",
    re: /within 60 days of the date of this order, to either:?(?: \(1\) show cause as to why [^,(]{0,140})?/ },
  { key: "adequacy-report", label: "30-day report on serving large loads with adequate generation", reform: "adequacy",
    re: /an informational report on how \S+ intends to ensure that adequate generation will be available to serve existing and new large loads/ },
];
function common(slug, item) {
  const file = join(ROOT, "docs", "reading", slug, "source.json");
  if (!existsSync(file)) return [];
  const pages = JSON.parse(readFileSync(file, "utf8")).pages;
  return COMMON.map((c) => {
    for (const p of pages) {
      const m = c.re.exec(p.text.replace(/\s+/g, " "));
      if (m) return { id: item + "-" + c.key, label: c.label, reform: c.reform, para: null, pg: p.page, quote: m[0].trim() };
    }
    throw Error(slug + ": no page carries the " + c.key + " directive");
  });
}

export function buildAnchors(D) {
  const orders = [...D.dockets, D.colocation].map((d) => {
    const item = d.item.toLowerCase();
    const slug = d.pdf.replace(/^orders\//, "").replace(/\.pdf$/, "");
    const seen = new Set();
    const anchors = (d.dir || []).map((x) => {
      let id = item + "-" + idOf(x.t);
      while (seen.has(id)) id += "-2";
      seen.add(id);
      // Each directive names its reform category in data.js; a missing or unknown key fails the build.
      const reform = x.reform;
      if (!REFORMS.has(reform)) throw Error(d.item + " directive \"" + x.t + "\" has reform " + JSON.stringify(reform));
      return { id, label: x.t, reform, para: x.p, pg: x.pg, quote: x.q };
    });
    if (d.item !== "E-2") anchors.unshift(...common(slug, item));
    return { item: d.item, rto: d.rto, docket: d.docket, slug, cite: d.cite || null, status: d.status || null, anchors };
  });
  return {
    note: "Generated by tools/build-order-anchors.mjs from data.js (dockets[].dir and colocation.dir). Do not edit; edit data.js and rebuild.",
    orders,
  };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = JSON.stringify(buildAnchors(loadData()), null, 1) + "\n";
  if (process.argv.includes("--check")) {
    if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) { console.error("order-anchors.json is stale: run node tools/build-order-anchors.mjs"); process.exit(1); }
    console.log("order-anchors.json is current.");
  } else { writeFileSync(OUT, text); console.log("Wrote", OUT.replace(ROOT + "/", "")); }
}
